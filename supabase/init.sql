-- Supabase initialization script for the Gomel region project
-- This script creates the relational schema, policies and storage buckets
-- expected by the frontend. Run it inside the SQL editor of your Supabase
-- project before first use.

-- Required extensions -------------------------------------------------------
create extension if not exists "pgcrypto";

-- Utility trigger -----------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

-- Profiles -----------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  username text not null,
  role text not null default 'user',
  avatar_url text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint username_min_length check (char_length(username) >= 3)
);

drop trigger if exists set_profiles_updated_at on public.profiles;
create trigger set_profiles_updated_at
before update on public.profiles
for each row
execute function public.set_updated_at();

alter table public.profiles enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'profiles'
      and policyname = 'Allow public profile read'
  ) then
    create policy "Allow public profile read"
      on public.profiles
      for select
      using (true);
  end if;
end;
$$;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'profiles'
      and policyname = 'Allow self profile insert'
  ) then
    create policy "Allow self profile insert"
      on public.profiles
      for insert
      with check (auth.uid() = id);
  end if;
end;
$$;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'profiles'
      and policyname = 'Allow self profile update'
  ) then
    create policy "Allow self profile update"
      on public.profiles
      for update
      using (auth.uid() = id)
      with check (auth.uid() = id);
  end if;
end;
$$;

-- Automatically create profile rows for new auth users ----------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  metadata jsonb := new.raw_user_meta_data;
  safe_email text := new.email;
  safe_role text := coalesce(nullif(metadata->>'role', ''), 'user');
  safe_username text;
begin
  safe_username := coalesce(
    nullif(metadata->>'username', ''),
    case
      when safe_email is not null and position('@' in safe_email) > 1 then split_part(safe_email, '@', 1)
      else 'user_' || left(new.id::text, 8)
    end
  );

  insert into public.profiles (id, email, username, role)
  values (new.id, safe_email, safe_username, safe_role)
  on conflict (id) do update
    set email = excluded.email,
        username = excluded.username,
        role = excluded.role;

  return new;
end;
$$;

drop trigger if exists handle_new_user on auth.users;
create trigger handle_new_user
after insert on auth.users
for each row
execute function public.handle_new_user();

