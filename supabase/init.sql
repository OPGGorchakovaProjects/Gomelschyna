-- Storage buckets ----------------------------------------------------------
do $$
begin
  if not exists (
    select 1 from storage.buckets where id = 'images'
  ) then
    perform storage.create_bucket('images', true);
  end if;
end;
$$;

do $$
begin
  if not exists (
    select 1 from storage.buckets where id = 'avatars'
  ) then
    perform storage.create_bucket('avatars', true);
  end if;
end;
$$;

-- Storage policies for images bucket

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'Allow public read access to images'
  ) then
    create policy "Allow public read access to images"
      on storage.objects
      for select
      using (bucket_id = 'images');
  end if;
end;
$$;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'Allow admins full access to images'
  ) then
    create policy "Allow admins full access to images"
      on storage.objects
      for all
      using (
        bucket_id = 'images'
        and exists (
          select 1
          from public.profiles p
          where p.id = auth.uid()
            and p.role = 'admin'
        )
      )
      with check (
        bucket_id = 'images'
        and exists (
          select 1
          from public.profiles p
          where p.id = auth.uid()
            and p.role = 'admin'
        )
      );
  end if;
end;
$$;

-- Storage policies for avatars bucket

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'Allow public read access to avatars'
  ) then
    create policy "Allow public read access to avatars"
      on storage.objects
      for select
      using (bucket_id = 'avatars');
  end if;
end;
$$;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'Allow users to manage their avatars'
  ) then
    create policy "Allow users to manage their avatars"
      on storage.objects
      for all
      using (
        bucket_id = 'avatars'
        and auth.uid() is not null
        and split_part(name, '/', 2) = auth.uid()::text
      )
      with check (
        bucket_id = 'avatars'
        and auth.uid() is not null
        and split_part(name, '/', 2) = auth.uid()::text
      );
  end if;
end;
$$;

-- Helper view for ratings --------------------------------------------------
create or replace view public.object_ratings as
select
  vp.object_id,
  avg(vp.rating) as average_rating,
  count(vp.rating) filter (where vp.rating is not null) as rating_count
from public.visited_places vp
where vp.rating is not null
group by vp.object_id;

-- Reset default grants for the ratings view
revoke all on public.object_ratings from public;
-- Allow everyone to read aggregated ratings
grant select on public.object_ratings to anon;
grant select on public.object_ratings to authenticated;
